function traitKey(value: string): string {
    const key = value.replace(/^t_/i, '').trim().replace(/_/g, ' ').toUpperCase();
    if (key === 'S.H.I.E.L.D.') return 'S.H.I.E.L.D';
    // ModelTrait.GetInfoTraits strips exclamation marks from engine UI keys.
    if (key === 'CHASE' || key === 'TRAP') return key + '!';
    return key;
}

export function koTraitSource(value: string): 'verified'|'rule'|'pending'|'unknown' {
    const key = traitKey(value);
    if (Object.prototype.hasOwnProperty.call(verifiedKoTraits,key)) return 'verified';
    if (Object.prototype.hasOwnProperty.call(ruleKoTraits,key)) return 'rule';
    if (Object.prototype.hasOwnProperty.call(pendingKoTraits,key)) return 'pending';
    return 'unknown';
}

export function koTraitLabel(value: string): string {
    const key = traitKey(value);
    const source = koTraitSource(value);
    if (source === 'verified') return verifiedKoTraits[key];
    if (source === 'rule') return ruleKoTraits[key];
    return key;
}
